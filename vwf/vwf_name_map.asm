;; =============================================================
;; Typed-name glyph mapping for the dialogue VWF (called for every glyph of the dialogue engine)
;; =============================================================

;; -------------------------------------------------------------
;; vwf_name_map(a0 = glyph code as passed to the emitter: single byte < 0x80 or glyph | 0x8000)
;; Typed names are stored as original glyph indices (full-width Latin letters, digits, punctuation, the
;; full-width space). In English text these are drawn as VWF characters instead of 16 px glyphs.
;; Returns v0 = VWF byte (ASCII + VWF_CHAR_BIAS) or a0 unchanged. Clobbers t0-t6.
;; Tables: vwf_name_lc (glyph 0x723..0x745 -> ASCII or 0), vwf_name_sym ({u16 glyph, u8 ascii, u8 0}, 0 ends)
;; (generated by tools/name_grid.py)
;; -------------------------------------------------------------
vwf_name_map:
    sltiu   t0, a0, 0x80                ; single byte glyph
    andi    t1, a0, 0x8000              ; or two-byte glyph
    or      t0, t0, t1
    beqz    t0, @@same                  ; 0x80-0x7FFF = already a VWF byte: leave
    andi    t1, a0, 0x7FF               ; t1 = glyph index
    beqz    t1, @@same                  ; glyph 0 (full-width space) stays 16 px: Japanese layouts rely on it
    nop
    addiu   t2, t1, -0xA6               ; A-Z
    sltiu   t3, t2, 26
    beqz    t3, @@not_upper
    nop
    jr      ra
    addiu   v0, t2, 0x41 + VWF_CHAR_BIAS
@@not_upper:
    addiu   t2, t1, -0xC0               ; 0-9
    sltiu   t3, t2, 10
    beqz    t3, @@not_digit
    nop
    jr      ra
    addiu   v0, t2, 0x30 + VWF_CHAR_BIAS
@@not_digit:
    addiu   t2, t1, -0x723              ; a-z (interleaved with kanji codes)
    sltiu   t3, t2, 35
    beqz    t3, @@not_lower
    nop
    la      t4, vwf_name_lc
    addu    t4, t4, t2
    lbu     t5, 0(t4)
    nop
    beqz    t5, @@same
    nop
    jr      ra
    addiu   v0, t5, VWF_CHAR_BIAS
@@not_lower:
    la      t4, vwf_name_sym
@@sym_loop:
    lhu     t5, 0(t4)
    nop
    beqz    t5, @@same
    nop
    bne     t5, t1, @@sym_loop
    addiu   t4, t4, 4
    lbu     v0, -2(t4)                  ; t4 already advanced: ascii byte of the matching entry
    nop
    jr      ra
    addiu   v0, v0, VWF_CHAR_BIAS
@@same:
    jr      ra
    move    v0, a0
