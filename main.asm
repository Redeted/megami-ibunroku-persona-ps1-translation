;; --- Character encoding tables ---
;; persona.tbl is generated: edit tools/font_map.tsv, run tools/make_tbl.py
;;   00-7F = glyph 0x000-0x07F, 80-87 xx = glyph 0x080-0x7FF, FF xx = control
;;   ASCII letters/digits/punctuation alias the font's full-width glyphs
;;   Control codes: <FFxx>, raw bytes: <xx>, unnamed glyphs: <Gxxx>
;;   .string terminator is FF01 (main-EXE menu strings); dialogue blocks end
;;   with other codes (TALK: FFF5/FFFC, events: FF02), so use .stringn there
