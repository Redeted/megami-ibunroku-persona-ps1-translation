"""Equipment-list header strings (hit counts, ALL, 攻撃 / 命中 / 防御 / 回避) in the ADV / DNG / S2D overlays.

  python tools/statmsg.py     write build/statmsg_<ovl>.asm (included in each overlay section of main.asm)

Layout (same in the three overlays, RAM address differs): 19 dialogue-format strings (FF01 end, leading 00 = full-width
space) packed back to back, 0x00 00 80 C1 81 4B FF 01 = "　　１回" first, and a table of 19 word pointers to them that
precedes the next data block. The weapon-list header prints "攻撃 8 命中11 2回": the code draws these strings through the
dialogue engine at fixed positions (so English goes through the dialogue VWF); the numbers are drawn by the code itself.
English strings are re-packed in the same byte span and the pointers rewritten.
"""
import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import etext   # noqa: E402

ROOT = etext.ROOT
B = 0x800643C4
NL = chr(10)
FIRST = bytes.fromhex('0000 80c1 814b ff01'.replace(' ', ''))     # "　　１回"
N = 19

EN = [
    "　1 hit", "　2 hits", "　3 hits", "　4 hits", "　5 hits", "　6 hits", "　7 hits",
    "0-1 hits", "1-3 hits", "2-4 hits", "3-5 hits", "4-6 hits", "5-7 hits", "0-7 hits",
    "　ALL", "ATK", "　HIT ", "DEF", "　EVA ",
]
assert len(EN) == N


def overlay(name):
    d = open(os.path.join(ROOT, 'original', name + '.BIN'), 'rb').read()
    s0 = d.index(FIRST)
    ptr0 = d.index(struct.pack('<I', B + s0))
    ptrs = [struct.unpack_from('<I', d, ptr0 + 4 * i)[0] - B for i in range(N)]
    ends = [d.index(b'\xff\x01', p) + 2 for p in ptrs]
    assert ptrs == sorted(ptrs) and all(ends[i] <= ptrs[i + 1] + 3 for i in range(N - 1)), name   # in order (slots may be padded)
    return d, ptr0, ptrs[0], ends[-1]


def main():
    data = b''.join(etext.encode(t) for t in EN)
    for name in ('ADV', 'DNG', 'S2D'):
        d, ptr0, a, e = overlay(name)
        if len(data) > e - a:
            raise SystemExit(f'statmsg: {len(data)} bytes > slot {e - a} in {name}')
        out = [f';; generated by tools/statmsg.py - do not edit ({name})' + NL]
        out.append(f'.org {B + a:#x}{NL}    .byte ' + ', '.join(f'0x{x:02X}' for x in data + bytes(e - a - len(data))) + NL)
        pos = a
        for i, t in enumerate(EN):
            out.append(f'.org {B + ptr0 + 4 * i:#x}{NL}    .word {B + pos:#x}{NL}')
            pos += len(etext.encode(t))
        open(os.path.join(ROOT, 'build', f'statmsg_{name.lower()}.asm'), 'w', newline=NL).write(''.join(out))
    print(f'statmsg: {len(EN)} strings, {len(data)} bytes')


if __name__ == '__main__':
    main()
