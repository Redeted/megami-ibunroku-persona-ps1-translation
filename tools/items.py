"""Item names of SLPS_005.00 (shown by the field item pick-up, menus and shops).

  python tools/items.py dump     write/refresh translation/strings/ITEMS.tsv (keeps the `en` column)
  python tools/items.py build    QA + generate build/items.asm (included by main.asm)

Layout (RAM, resident main EXE; file offset = addr - 0x80010000 + 0x800): 163 records of 0x20 bytes from
0x8004441C; the name is at record+0x10, single-byte glyph indices (the game's own font numbering).
The names are drawn by the overlay's text-object renderer with the 8x12 "small font" page (VRAM x=896,y=256), which
has katakana/hiragana, UPPERCASE A-Z, 0-9 and  / : - + x = & ! ? . ( ) , like the existing English UI labels
(TIME, MONEY, LEVEL ...). Latin letters are given as the full-width glyph codes (A = 0xA6 ... 0, 1 = 0xC0, 0xC1 ...);
glyph 0 is a blank cell (space). Verified in game 2026-10-04 (MEDICINE).

The name field is exactly 10 bytes: a 10-glyph name has NO terminator (byte +10 is a data byte), shorter names end
with 0xFF.
`en` rules: A-Z, 0-9, space, - . ' / :  (lower case is upper-cased). Names longer than 10 characters are CUT to 10
(user decision 2026-10-06: the full official name stays in the TSV, the screens show the first 10 glyphs).
Empty `en` = left Japanese. Records 163-381 (equipment) share the layout; their stats follow the name.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import etext  # noqa: E402

ROOT = etext.ROOT
BASE = 0x80010000 - 0x800
FIRST = 0x8004442C                 # name of record 0
STRIDE = 0x20
COUNT = 382                        # 0-162 items (..0x8004586C メス), 163-381 equipment: weapons, guns, ammo, armor (..0x800473CC)
TSV = os.path.join(ROOT, 'translation', 'strings', 'ITEMS.tsv')
OUT = os.path.join(ROOT, 'build', 'items.asm')
NL = chr(10)
# small-font page codes (NOT the dialogue font numbering: from 0xCD on the pages differ, and the battle page
# (VRAM 960,256) has HP/SP icons at 0xCD+): / : - exist in every page; . and ' are redrawn kana cells
# (tools/smallfont_lc.py PUNCT); & ! ? exist only in the field page (0xD1-0xD3) and are refused.
EXTRA = {' ': 0, '/': 0xCA, ':': 0xCB, '-': 0xCC}


def glyph(c):
    if 'A' <= c <= 'Z':
        return etext.char2g[chr(0xFF21 + ord(c) - 0x41)]
    if '0' <= c <= '9':
        return etext.char2g[chr(0xFF10 + ord(c) - 0x30)]
    if c in EXTRA:
        return EXTRA[c]
    import smallfont_lc
    return smallfont_lc.code(c)        # a-z . '


def records():
    d = open(os.path.join(ROOT, 'original', 'SLPS_005.00'), 'rb').read()
    out = []
    r = FIRST - BASE
    for k in range(COUNT):
        assert k >= 163 or d[r - 4:r - 2] == b'\xff\x01'      # equipment records end differently
        nm = d[r:r + 10]                    # the name field is exactly 10 bytes
        end = nm.index(b'\xff') if b'\xff' in nm else 10
        out.append((r + BASE, bytes(nm[:end])))
        r += STRIDE
    return out


def ja(b):
    return ''.join(etext.glyph.get(x, '<%02X>' % x) for x in b)


def read_tsv():
    rows = {}
    if os.path.exists(TSV):
        for line in open(TSV, encoding='utf-8').read().split(NL)[1:]:
            c = line.rstrip('\r').split('\t')
            if len(c) >= 4 and c[0].isdigit():
                rows[int(c[0])] = c[3]
    return rows


def dump():
    old = read_tsv()
    with open(TSV, 'w', encoding='utf-8', newline=NL) as o:
        o.write('idx\taddr\tja\ten' + NL)
        for k, (a, nm) in enumerate(records()):
            o.write(f'{k}\t{a:08X}\t{ja(nm)}\t{old.get(k, "")}' + NL)
    print('wrote', TSV)


def build():
    recs = records()
    en = read_tsv()
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    n = cut = 0
    with open(OUT, 'w', newline=NL) as o:
        o.write(';; generated by tools/items.py build - do not edit' + NL)
        for k, (a, nm) in enumerate(recs):
            t = en.get(k, '').strip()
            if not t:
                continue
            cap = 10
            t = t.upper()
            for c in t:
                if not (c in 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789' or c in EXTRA or c in ".'"):
                    raise SystemExit(f'items: {k} {t!r}: character {c!r} is not in the small font')
            if len(t) > cap:
                t = t[:cap].rstrip(' ')
                cut += 1
            codes = [glyph(c) for c in t]
            assert all(0 <= x < 0x100 for x in codes), (k, t, codes)
            data = (codes + [0xFF] + [0] * 10)[:10]       # exactly the 10-byte field; byte +10 is data, never touched
            o.write(f'; {k} {t}{NL}.org {a:#x}{NL}    .byte ' + ', '.join(f'0x{x:02X}' for x in data) + NL)
            n += 1
    print(f'items: {n}/{len(recs)} translated ({cut} cut to 10) -> {OUT}')


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    {'dump': dump, 'build': build}[sys.argv[1] if len(sys.argv) > 1 else 'build']()
