"""Script-style messages embedded in the ADV / DNG overlays (outside the E files): `FF 55 00 00 <ptr>` text commands.

  python tools/scriptmsg.py     write build/scriptmsg_adv.asm, build/scriptmsg_dng.asm (included in the overlay sections of main.asm)

Found 2026-10-07 (user: ADV 2D scene, Circle with nothing to interact with -> "何もないようだ" in Japanese). tools/s2dscript.py handles
the 61 boxes of the S2D overlay; the same command exists with exactly 3 targets in ADV.BIN and 2 in DNG.BIN (scan of every overlay,
2D/ and D0x/ data for `FF 55 00 00 ptr` pointing at text): nothing else of this type is left.
The slots are tiny (the Japanese is mostly 1-byte kana: 12 / 15 / 16 bytes incl. `FF02 FF01`) and the pointer words sit inside
the command stream, so the English is written IN PLACE (VWF text = 1 byte per letter) and abbreviated to fit:
  ADV 0x800B6C58 何もないようだ (It seems there is nothing)   -> "Nothing."          (8 letters)
  ADV 0x800B6C7C なにも　はいっていない (nothing inside)       -> "It's empty."      (11)
  ADV 0x800B6CA4 そちらからは<FF03>とれない (can't take it from that side) -> "Can't take." (11)
  DNG 0x8009A18C <FF09 12 00>の効果がきれた / 0x8009A1B4 <FF0A 73>の効果がきれた (<name>'s effect wore off) -> "<name> wore off" (9, no period: slot size)
FF09 takes 2 parameter bytes, FF0A one: ALL parameter bytes are kept (4 / 3 bytes). The static ids are item 0x12 (Core Shield) / skill 0x73 (Rifutoma).
The name inserts are printed by the DNG name printer 0x800753AC (dng/vwf_script.asm: name-insertion flag, FF0A through skill_name_copy).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import etext   # noqa: E402

ROOT = etext.ROOT
B = 0x800643C4
NL = chr(10)
# (overlay, RAM address, number of original bytes kept before the text (name codes), English)
MSGS = [
    ('ADV', 0x800B6C58, 0, "Nothing."),
    ('ADV', 0x800B6C7C, 0, "It's empty."),
    ('ADV', 0x800B6CA4, 0, "Can't take."),
    ('DNG', 0x8009A18C, 4, " wore off"),      # FF09 + 2-byte item id (0x12 ...)
    ('DNG', 0x8009A1B4, 3, " wore off"),      # FF0A + skill id (0x73 ...); keeping every id byte matters (2026-10-09: 3 / 2 kept ate the id)
]


RACE_OVERRIDE = {24: 'Majin'}      # 魔神皇 is unused; the PSP-style literal "Majinnou" does not fit the 6-letter slot


def race_titles():
    """The 26 kanji race names (16 px title of the ANALYZE screen, pointer table + 8-byte slots) of ADV / DNG / S2D."""
    en = {}
    for line in open(os.path.join(ROOT, 'translation', 'work', 'races_en.tsv'), encoding='utf-8').read().split(NL)[1:]:
        c = line.split(chr(9))
        if len(c) >= 3 and c[0].isdigit():
            en[int(c[0])] = RACE_OVERRIDE.get(int(c[0]), c[2])
    first = etext.encode('夜魔', end=None) + bytes((0xFF, 0x01))
    for ovl in ('ADV', 'DNG', 'S2D'):
        d = open(os.path.join(ROOT, 'original', ovl + '.BIN'), 'rb').read()
        s = d.index(first)
        lines = [f';; generated by tools/scriptmsg.py - do not edit ({ovl} race titles){NL}']
        for k in range(26):
            a = s + 8 * k
            b = etext.encode(en[k], end=None) + bytes((0xFF, 0x01))
            assert len(b) <= 8 and d[a + 4:a + 6] != b'', (k, en[k])
            lines.append(f'.org {B + a:#x}{NL}    .byte ' + ', '.join(f'0x{x:02X}' for x in b + bytes(8 - len(b))) + NL)
        open(os.path.join(ROOT, 'build', f'racetitles_{ovl.lower()}.asm'), 'w', newline=NL).write(''.join(lines))


def main():
    race_titles()
    out = {'ADV': [], 'DNG': []}
    for ovl, ram, keep, en in MSGS:
        d = open(os.path.join(ROOT, 'original', ovl + '.BIN'), 'rb').read()
        s = ram - B
        e = d.index(b'\xff\x01', s) + 2
        if d[e - 4:e] != b'\xff\x02\xff\x01':
            raise SystemExit(f'scriptmsg: {ram:#x}: unexpected end {d[e - 4:e].hex()}')
        b = d[s:s + keep] + etext.encode(en, end=None) + b'\xff\x02\xff\x01'
        if len(b) > e - s:
            raise SystemExit(f'scriptmsg: {ram:#x}: {len(b)} bytes > slot {e - s}')
        b += bytes(e - s - len(b))
        out[ovl].append(f'.org {ram:#x}{NL}    .byte ' + ', '.join(f'0x{x:02X}' for x in b) + NL)
    for ovl, lines in out.items():
        open(os.path.join(ROOT, 'build', f'scriptmsg_{ovl.lower()}.asm'), 'w', newline=NL).write(
            f';; generated by tools/scriptmsg.py - do not edit ({ovl}){NL}' + ''.join(lines))
    print(f'scriptmsg: {len(MSGS)} messages')


if __name__ == '__main__':
    main()
