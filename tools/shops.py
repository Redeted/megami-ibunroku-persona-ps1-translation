"""ADV shop lists: add new items (Emergency Exit) to shops without moving the tables.

  python tools/shops.py          print the shops + generate build/shops_adv.asm (included by main.asm, ADV section)

Layout (ADV.BIN, found 2026-11-09): table 0x800BABA8 = (count u8, start u8) for 17 shops; item ids (u16, 1-based) from
0x800BA888 and buy prices (u32) from 0x800BA34C, indexed by start + n (copied at shop open by 0x800AAFE0 / 0x800AB068
into 0x800EB590 / 0x800EB5D0, room for 24 entries). Shops whose list is the start of another shop's list (shop 10 =
first 10 of shop 11, 12 = first 10 of 13) can share that window, which frees enough entries for the additions while
the arrays keep their size (ITEM_CAP).
"""
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ADV = os.path.join(ROOT, 'original', 'ADV.BIN')
OUT = os.path.join(ROOT, 'build', 'shops_adv.asm')
BASE = 0x800643C4
TABLE, ITEMS, PRICES = 0x800BABA8, 0x800BA888, 0x800BA34C
SHOPS = 17
ITEM_CAP = 178                  # entries in the original arrays (the item array is followed by the 2nd shop table)
SHOP_MAX = 24                   # copy buffer 0x800EB5D0.. reaches the next variable at 0x800EB630
NL = chr(10)

EMERGENCY_EXIT = 112            # 1-based id of item 111 (slps_005.00/emergency_exit.asm)
CLEAN_SALT = 111                # 1-based id of item 110 (slps_005.00/emergency_exit.asm, dng/estoma.asm)
# shop -> [(insert position, item id, price)]: PSP prices (both 10000) in every Satomi Tadashi pharmacy (lists 10, 11,
# 16; lists 10 / 11 are also the Snow Queen school pharmacy E3/5: allowed, Emergency Exit is greyed in SQ dungeons).
# Same position: inserted in reverse order, so Clean Salt comes first.
DRUG = [(10, CLEAN_SALT, 10000), (10, EMERGENCY_EXIT, 10000)]
ADD = {
    10: DRUG,
    11: DRUG,
    16: [(8, CLEAN_SALT, 10000), (8, EMERGENCY_EXIT, 10000)],
}


# How a room opens a shop (found 2026-11-09): event-script command `FF 2A <store> 00` (ADV/E?.BIN; ADV interpreter
# 0x800AC260: opcode = byte 1 - 0x21 into the jump table 0x80065520, case 9 = 0x800AC390) calls the shop function
# 0x80099304(store). STORE table 0x800BAB5C = (menu type u8, list u8) x 38, copied to 0x800EB581 / 0x800EB580.
# Menu types: 0/1 = equipment lists 0-4 / 5-9, 2 = consumables (lists 10-16), 3 = Persona items, 4/5 = Kamentsurun
# gem exchange, 6-9 = Velvet Room, 10 = store 0x24 (fixed in the interpreter). Store -> list for type 2:
# 10->10, 11->11, 12->12, 13->13, 16->14, 17->15, 18->16.
# Consumable lists by place (event entries that open them; SQ = Snow Queen route, E3):
SHOP_NAMES = {
    10: 'Satomi Tadashi pharmacy, Tadashi\'s dad (E2/186, E2/209 = user slot 8; SQ: E3/5 school pharmacy)',
    11: 'Satomi Tadashi "call me Sato-chan" (E2/194; SQ: E3/5 school pharmacy, later list)',
    12: 'Tsurunkamen (E2/189, E2/208; SQ: E3/6 school festival stall)',
    13: 'Tsurunkamen, later list (E2/193; SQ: E3/6 school festival stall)',
    14: 'Convenience store (E0/18, E2/41, E2/103, E2/114-131)',
    15: 'Senrinmando candy shop, shopping street (E2/46, E2/52, E2/105, E2/111)',
    16: 'Satomi Tadashi, Tadashi\'s uncle (E2/47, E2/54, E2/106, E2/112)',
}


def read():
    d = open(ADV, 'rb').read()
    shops = []
    for s in range(SHOPS):
        n, st = d[TABLE - BASE + 2 * s], d[TABLE - BASE + 2 * s + 1]
        shops.append([(struct.unpack_from('<H', d, ITEMS - BASE + 2 * (st + i))[0],
                       struct.unpack_from('<I', d, PRICES - BASE + 4 * (st + i))[0]) for i in range(n)])
    return shops


def build():
    shops = read()
    for s, adds in ADD.items():
        for pos, item, price in sorted(adds, reverse=True):
            assert item not in [i for i, _ in shops[s]], (s, item)
            shops[s].insert(pos, (item, price))
    # pack: longest lists first; a list that is the start of an already placed one shares its window
    flat, where = [], {}
    for s in sorted(range(SHOPS), key=lambda k: -len(shops[k])):
        lst = shops[s]
        assert len(lst) <= SHOP_MAX, (s, len(lst))
        for t, st in where.items():
            if shops[t][:len(lst)] == lst:
                where[s] = st
                break
        else:
            where[s] = len(flat) if lst else 0
            flat += lst
    if len(flat) > ITEM_CAP:
        raise SystemExit(f'shops: {len(flat)} entries > {ITEM_CAP}')
    flat += [(0, 0)] * (ITEM_CAP - len(flat))
    with open(OUT, 'w', newline=NL) as o:
        o.write(';; generated by tools/shops.py - do not edit' + NL)
        o.write(f'.org 0x{TABLE:08X}' + NL)
        for s in range(SHOPS):
            o.write(f'    .byte {len(shops[s])}, {where[s]}' + NL)
        o.write(f'.org 0x{ITEMS:08X}' + NL)
        for i in range(0, ITEM_CAP, 12):
            o.write('    .halfword ' + ', '.join(str(x) for x, _ in flat[i:i + 12]) + NL)
        o.write(f'.org 0x{PRICES:08X}' + NL)
        for i in range(0, ITEM_CAP, 8):
            o.write('    .word ' + ', '.join(str(p) for _, p in flat[i:i + 8]) + NL)
    used = len([x for x in flat if x[0]])
    print(f'shops: {sum(len(v) for v in ADD.values())} additions, {used}/{ITEM_CAP} array entries -> {OUT}')
    return shops, where


if __name__ == '__main__':
    shops, where = build()
    if '-v' in sys.argv:
        for s in range(SHOPS):
            print(s, where[s], [i for i, _ in shops[s]])
