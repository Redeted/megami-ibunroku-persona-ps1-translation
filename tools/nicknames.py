"""Party nicknames (battle status panels, ...) in SLPS_005.00.

  python tools/nicknames.py dump     write/refresh translation/strings/NICKNAMES.tsv (keeps the `en` column)
  python tools/nicknames.py build    QA + generate build/nicknames.asm (included by main.asm)

9 character records of 0x28 bytes; the nickname is a 10-byte field after the halfwords 4F01 0000 6F01 (first field
0x800442B2 = the hero's default "ATLUS"), single-byte glyph indices of the game font like the item names
(tools/items.py: uppercase A-Z = 0xA6.., 0-9, glyph 0 = space; lowercase = codes 0xE0.., tools/smallfont_lc.py),
FF-terminated. Drawn with the 8x12 small font in the
battle status panels: at most 8 characters are visible and a longer name overwrites the next panel, the hyphen glyph is
not in that font (verified in game 2026-10-05).
The records are COPIED into the party data when a character joins (RAM 0x8005D7A3.., save data 0x801F1C6B..): a game
saved before this patch keeps the Japanese nicknames of members who had already joined.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import etext   # noqa: E402
import items   # noqa: E402
import smallfont_lc  # noqa: E402

ROOT = etext.ROOT
BASE = 0x80010000 - 0x800
FIRST = 0x800442B2
STRIDE = 0x28
COUNT = 9
FIELD = 10
MAXLEN = 8
TSV = os.path.join(ROOT, 'translation', 'strings', 'NICKNAMES.tsv')
OUT = os.path.join(ROOT, 'build', 'nicknames.asm')
NL = chr(10)
G2C = {v: k for k, v in etext.char2g.items()}


def records():
    d = open(os.path.join(ROOT, 'original', 'SLPS_005.00'), 'rb').read()
    out = []
    for i in range(COUNT):
        a = FIRST + STRIDE * i
        assert d[a - BASE - 2:a - BASE] == b'\x6f\x01', hex(a)
        f = d[a - BASE:a - BASE + FIELD]
        ja = ''.join(G2C.get(x, '?') for x in f.split(b'\xff')[0])
        out.append((i, a, ja))
    return out


def read_tsv():
    rows = {}
    if os.path.exists(TSV):
        for line in open(TSV, encoding='utf-8').read().split(NL)[1:]:
            c = line.rstrip('\r').split('\t')
            if len(c) >= 4 and c[0].isdigit():
                rows[int(c[0])] = c[3]
    return rows


def dump():
    old = read_tsv()
    with open(TSV, 'w', encoding='utf-8', newline=NL) as o:
        o.write('idx\tram\tja\ten' + NL)
        for i, a, ja in records():
            o.write(f'{i}\t{a:08X}\t{ja}\t{old.get(i, "")}' + NL)
    print('wrote', TSV)


def build():
    en = read_tsv()
    with open(OUT, 'w', newline=NL) as o:
        o.write(';; generated by tools/nicknames.py build - do not edit' + NL)
        n = 0
        for i, a, ja in records():
            t = en.get(i, '').strip()
            if not t:
                continue
            if len(t) > MAXLEN:
                raise SystemExit(f'nicknames: {i} {t!r} is longer than {MAXLEN}')
            for c in t:
                if not ('A' <= c <= 'Z' or 'a' <= c <= 'z' or '0' <= c <= '9' or c in " .-/:'"):
                    raise SystemExit(f'nicknames: {i} {t!r}: {c!r} is not in the small font')
            b = bytes(smallfont_lc.code(c) if 'a' <= c <= 'z' else items.glyph(c) for c in t) + b'\xff'
            b += bytes(FIELD - len(b))
            o.write(f'.org {a:#x}{NL}    .byte ' + ', '.join(f'0x{x:02X}' for x in b) + NL)
            n += 1
    print(f'nicknames: {n}/{COUNT} -> {OUT}')


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    {'dump': dump, 'build': build}[sys.argv[1] if len(sys.argv) > 1 else 'build']()
