"""Build the variable-width English font used by the dialogue VWF hack.

Input : font/spleen-8x16.bdf (Spleen 8x16, BSD-2-Clause, see font/SPLEEN-LICENSE)
        font/vwf_overrides.txt (optional: per-glyph hand edits, see below)
Output: font/vwf_font.bin   - 95 glyphs (0x20-0x7E), 16 rows x 1 byte, MSB = leftmost
                              pixel, ink cropped to the left edge (preview/tools)
        font/vwf_width.bin  - 95 bytes, pen advance in pixels
        font/vwf_index.bin  - 95 u16: offset from FONT.BIN start of each glyph's
                              14 stored rows (rows 1-14; rows 0 and 15 are blank)
        font/vwf_glyphs.asm - armips: writes the stored rows into unused
                              FONT.BIN glyph slots (filler/blank glyphs)
        font/vwf_preview.png
Usage : python tools/make_vwf_font.py ["sample text"]
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_DIR = os.path.join(ROOT, "font")
FIRST, LAST = 0x20, 0x7E
SPACE_ADVANCE = 4
LETTER_GAP = 1  # blank columns after the ink


def load_bdf(path):
    glyphs, cur, rows = {}, None, None
    for line in open(path, encoding="ascii"):
        tok = line.split()
        if not tok:
            continue
        if tok[0] == "ENCODING":
            cur = int(tok[1])
        elif tok[0] == "BITMAP":
            rows = []
        elif tok[0] == "ENDCHAR":
            if cur is not None and FIRST <= cur <= LAST:
                glyphs[cur] = rows
            cur, rows = None, None
        elif rows is not None:
            rows.append(int(tok[0], 16))
    return glyphs


def load_overrides(path):
    """Override file: blocks of 'char X' followed by 16 lines of '.'/'#' (8 wide)."""
    out = {}
    if not os.path.exists(path):
        return out
    lines = [l.rstrip("\n") for l in open(path, encoding="utf-8")]
    i = 0
    while i < len(lines):
        if lines[i].startswith("char "):
            ch = lines[i][5]
            out[ord(ch)] = [int(l.ljust(8, ".")[:8].replace(".", "0").replace("#", "1"), 2)
                            for l in lines[i + 1:i + 17]]
            i += 17
        else:
            i += 1
    return out


def build():
    glyphs = load_bdf(os.path.join(FONT_DIR, "spleen-8x16.bdf"))
    glyphs.update(load_overrides(os.path.join(FONT_DIR, "vwf_overrides.txt")))
    data, widths = bytearray(), bytearray()
    for c in range(FIRST, LAST + 1):
        rows = glyphs.get(c, [0] * 16)
        ink = 0
        for r in rows:
            ink |= r
        if ink == 0:
            data += bytes(16)
            widths.append(SPACE_ADVANCE)
            continue
        left = next(b for b in range(8) if ink & (0x80 >> b))
        right = max(b for b in range(8) if ink & (0x80 >> b))
        data += bytes((r << left) & 0xFF for r in rows)
        widths.append(right - left + 1 + LETTER_GAP)
    return data, widths


# Unused FONT.BIN glyph slots (filler "*" or blank glyphs that no text uses),
# as contiguous runs [first, last]. Stored glyphs are packed back to back.
FONT_SLOT_RUNS = [(0x0F7, 0x10F), (0x7F2, 0x7FF), (0x64E, 0x64E), (0x65F, 0x65F), (0x662, 0x662)]
STORED_ROWS = range(1, 15)


def place(data):
    """Pack each glyph's rows 1-14 into the slot runs; return (index, asm)."""
    per = len(STORED_ROWS)
    runs = [[a * 32, (b + 1) * 32] for a, b in FONT_SLOT_RUNS]
    index, asm = [], [";; generated by tools/make_vwf_font.py - do not edit"]
    run = 0
    for g in range(len(data) // 16):
        rows = data[g * 16:(g + 1) * 16]
        assert rows[0] == 0 and rows[15] == 0, f"glyph {g + FIRST:#x} uses row 0 or 15"
        while runs[run][0] + per > runs[run][1]:
            run += 1
            if run == len(runs):
                raise SystemExit("VWF font does not fit in the free FONT.BIN slots")
        off = runs[run][0]
        runs[run][0] += per
        index.append(off)
        asm.append(f".org FONT_GLYPHS_ADDR + 0x{off:04X}  ; {chr(g + FIRST)!r}")
        asm.append("    .byte " + ", ".join(f"0x{rows[r]:02X}" for r in STORED_ROWS))
    return index, "\n".join(asm) + "\n"


def preview(data, widths, text, path):
    from PIL import Image
    pal = {0: (32, 96, 48), 1: (0, 0, 0), 2: (240, 240, 240), 3: (240, 240, 240)}
    W = 240
    lines, line, x = [], "", 0
    for word in text.split(" "):
        wlen = sum(widths[ord(c) - FIRST] for c in word)
        if x + wlen > W and line:
            lines.append(line.rstrip()); line, x = "", 0
        line += word + " "; x += wlen + SPACE_ADVANCE
    lines.append(line.rstrip())
    img = Image.new("RGB", (W + 8, 16 * len(lines) + 8), pal[0])
    px = img.load()
    for li, s in enumerate(lines):
        buf = [[0] * (W + 4) for _ in range(17)]
        x = 0
        for c in s:
            g = data[(ord(c) - FIRST) * 16:(ord(c) - FIRST + 1) * 16]
            for r in range(16):
                for b in range(8):
                    if g[r] & (0x80 >> b):
                        if x + b + 2 < W + 4:
                            buf[r + 1][x + b + 2] |= 1
                        buf[r][x + b] |= 2
            x += widths[ord(c) - FIRST]
        for r in range(16):
            for cx in range(W):
                px[4 + cx, 4 + li * 16 + r] = pal[buf[r][cx]]
    img = img.resize((img.width * 3, img.height * 3), Image.NEAREST)
    img.save(path)
    return lines


if __name__ == "__main__":
    data, widths = build()
    open(os.path.join(FONT_DIR, "vwf_font.bin"), "wb").write(data)
    open(os.path.join(FONT_DIR, "vwf_width.bin"), "wb").write(widths)
    index, asm = place(data)
    open(os.path.join(FONT_DIR, "vwf_index.bin"), "wb").write(b"".join(o.to_bytes(2, "little") for o in index))
    open(os.path.join(FONT_DIR, "vwf_glyphs.asm"), "w", newline="\n").write(asm)
    sample = sys.argv[1] if len(sys.argv) > 1 else (
        "Mark: \"Persona-sama\"? Like that's gonna show you your future! "
        "If it were that easy, nobody would ever worry. Quick brown fox jumps over 1,234 lazy dogs.")
    lines = preview(data, widths, sample, os.path.join(FONT_DIR, "vwf_preview.png"))
    print(f"{len(widths)} glyphs, {len(data)} bytes; avg advance "
          f"{sum(widths) / len(widths):.2f}px; sample lines: {len(lines)}")
    for l in lines:
        print(f"  {sum(widths[ord(c) - FIRST] for c in l):3}px  {l}")
