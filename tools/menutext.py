"""Field-menu strings left in Japanese in the ADV / DNG / S2D overlays (FORM list, Persona / card menus, item menu).

  python tools/menutext.py     write build/menutext_<ovl>.asm (included in each overlay section of main.asm)

The three overlays hold the same block (ADV RAM 0x800B22B4.., DNG / S2D at file offset - 0x17510 / 0x14980; found by content).
Two kinds of strings (same two encodings as tools/cfgtext.py / tools/sysmsg.py):
  tile strings: 1 byte per 8x12 small-font cell (kana cells = the game's kana, A-Z / a-z / digits via tools/skills.glyph, 0 = blank),
                drawn with a fixed cell count (the Japanese length), so English is padded with blank cells to the same length;
  dialogue strings (FF01 end): VWF ASCII (etext.encode), one byte per letter.
FORM list: the code (S2D 0x80081714) draws 8 cells of the name, then writes the letter A/B/C at cell 9; the English name is
right-aligned in the 8 cells ("Form" -> "    Form A").
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import etext    # noqa: E402
import skills   # noqa: E402

ROOT = etext.ROOT
B = 0x800643C4
NL = chr(10)
DELTA_LOW = {'ADV': 0, 'DNG': 0x17510, 'S2D': 0x14980}    # file offset of the block = ADV offset - delta

# (Japanese bytes (hex), kind, English, right-align)
T = [
    ('987a60662d1a360d', 'tile', 'Remove', False),               # ペルソナをはずす
    ('6d9ecc73cc5da47f', 'tile', 'Form', True),                  # フォーメーション (+ A/B/C drawn by the code)
    ('525364723c06021c08', 'tile', 'Item Heal', False),          # アイテムでかいふく
    ('987a60663c06021c08', 'tile', 'Pers.Heal', False),          # ペルソナでかいふく (FF0C follows)
    ('5e80987a5780cc808f2f01281f0e2e', 'dlg', 'No Spell Cards.', False),   # スペルカードがありません (FF01 follows)
    ('5e80987a5780cc808f82c081fa', 'dlg', 'Delete Card', False),   # スペルカード削除 (FF01 follows)
]


def tile(t, n, right):
    b = bytes(skills.glyph(c) for c in t)
    if len(b) > n:
        raise SystemExit(f'menutext: {t!r} is {len(b)} cells > {n}')
    return (bytes(n - len(b)) + b) if right else (b + bytes(n - len(b)))


def main():
    for ovl, delta in DELTA_LOW.items():
        d = open(os.path.join(ROOT, 'original', ovl + '.BIN'), 'rb').read()
        out = [f';; generated by tools/menutext.py - do not edit ({ovl}){NL}']
        for hx, kind, en, right in T:
            ja = bytes.fromhex(hx)
            i = d.find(ja)
            if i < 0 or d.find(ja, i + 1) >= 0 and ovl != 'ADV':
                raise SystemExit(f'menutext: {hx} not found / not unique in {ovl}')
            n = len(ja)
            if kind == 'tile':
                b = tile(en, n, right)
            else:
                b = etext.encode(en, end=None)
                if len(b) > n:
                    raise SystemExit(f'menutext: {en!r} is {len(b)} bytes > {n}')
                b += bytes(n - len(b)) if False else b''
                # shorter text: FF01 right after it, the rest of the old slot is left (never read)
                b += bytes((0xFF, 0x01))
                if len(b) > n + 2:
                    raise SystemExit(f'menutext: {en!r} too long')
                b += bytes(n + 2 - len(b))
            out.append(f'.org {B + i:#x}{NL}    .byte ' + ', '.join(f'0x{x:02X}' for x in b) + NL)
        open(os.path.join(ROOT, 'build', f'menutext_{ovl.lower()}.asm'), 'w', newline=NL).write(''.join(out))
    print(f'menutext: {len(T)} strings x 3 overlays')


if __name__ == '__main__':
    main()
