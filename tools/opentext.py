"""Title-screen LOAD GAME screens: memory-card messages (OPEN.EXE) and the SLOT 1 / SLOT 2 buttons (OPEN.BIN atlas).

  python tools/opentext.py     write build/open_exe.asm, build/gfx/open_474C0.bin (+ preview PNG)

Messages: OPEN.EXE RAM 0x800A0134.. (file offset = RAM - 0x800A0000 + 0x20800), 11 blocks of 16-bit glyph indices printed
into a COLS x ROWS grid of 16 px cells by 0x80085C30 / 0x800861D0 (cols/rows per block below, from the callers). English uses
the full-width Latin glyphs of the game font (A = 0xA6, a = 0x723.., blank = 0) and has to fit the grid: <= COLS characters
per row. The file number of the "file N is corrupted" message is drawn by the code over the cell where the Japanese has
the placeholder "０" (index 5 of row 1), so that cell stays "０".
Buttons: OPEN.BIN TIM 0x474C0 (4bpp 256x32, VRAM 704,256), row 2 holds the bitmap "スロット1" / "スロット2" (also used for the
tab on the save list). "SLOT 1/2" is composed from the letters of the same atlas (S, L, O from "YES"/"LOAD", the digits
from the Japanese row, T drawn here), coloured with the gradient of the original kana.
"""
import os
import struct
import sys
import collections

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import etext      # noqa: E402
import tim        # noqa: E402
import menu_gfx   # noqa: E402

ROOT = tim.ROOT
NL = chr(10)
FO = lambda ram: ram - 0x800A0000 + 0x20800

# (RAM, cols, rows, [English rows])
MSGS = [
    (0x800A0134, 12, 2, ['Select the', 'card slot']),
    (0x800A0164, 13, 1, ['No card found']),
    (0x800A0180, 13, 1, ['Card error']),
    (0x800A0198, 13, 2, ['Card is not', 'formatted']),
    (0x800A01CC, 12, 3, ['Loading data', "Don't remove", 'the card']),
    (0x800A0214, 12, 2, ['File 0 data', 'is corrupted']),      # the 0 is the placeholder cell (index 5)
    (0x800A0244, 12, 1, ['No save data']),
    (0x800A025C, 11, 2, ['Card is not', 'inserted']),
    (0x800A0288, 10, 2, ['Slot 1 has', 'no space']),
    (0x800A02B0, 10, 2, ['Slot 2 has', 'no space']),
    (0x800A02D8, 13, 3, ['Suspend data.', 'Deleted from', 'card on load']),
]
EXTRA = {'.': '．', '?': '？', '!': '！', '-': '－', "'": '’', ',': '，'}


def glyph(c):
    if c == ' ':
        return 0
    if 'A' <= c <= 'Z':
        return etext.char2g[chr(0xFF21 + ord(c) - 65)]
    if 'a' <= c <= 'z':
        return etext.char2g[chr(0xFF41 + ord(c) - 97)]
    if '0' <= c <= '9':
        return etext.char2g[chr(0xFF10 + ord(c) - 48)]
    return etext.char2g[EXTRA[c]]


def messages():
    d = open(os.path.join(ROOT, 'original', 'EXE', 'OPEN.EXE'), 'rb').read()
    out = [';; generated by tools/opentext.py - do not edit' + NL]
    for ram, cols, rows, lines in MSGS:
        assert len(lines) == rows, hex(ram)
        ws = []
        for ln in lines:
            if len(ln) > cols:
                raise SystemExit(f'opentext: {ln!r} is {len(ln)} chars, {cols} columns')
            ws += [glyph(c) for c in ln.ljust(cols)]
        n = cols * rows
        out.append(f'; {" / ".join(lines)}{NL}.org OPEN_EXE_ADDR + {FO(ram):#x}{NL}    .halfword ' + ', '.join(f'{w:#x}' for w in ws) + NL)
    open(os.path.join(ROOT, 'build', 'open_exe.asm'), 'w', newline=NL).write(''.join(out))


T_GLYPH = ['######', '######', '..##..', '..##..', '..##..', '..##..', '..##..', '..##..', '..##..', '..##..', '..##..']


D1 = ['..##..', '.###..', '####..', '..##..', '..##..', '..##..', '..##..', '..##..', '..##..', '######', '######']
D2 = ['.####.', '######', '##..##', '....##', '...###', '..###.', '.###..', '###...', '##....', '######', '######']


def buttons():
    from PIL import Image
    d = open(tim.locate('OPEN.BIN'), 'rb').read()
    t = tim.parse(d, 0x474C0)
    w, h = t['px_w'], t['h']
    pix = menu_gfx.unpack(d, t)

    def mask(x0, x1, y0, y1):
        return [[pix[y * w + x] != 0 for x in range(x0, x1 + 1)] for y in range(y0, y1 + 1)]
    glyphs = {
        'S': mask(78, 83, 3, 13), 'L': mask(153, 158, 3, 13), 'O': mask(11, 16, 3, 13),
        'T': [[c == '#' for c in row] for row in T_GLYPH],
        '1': [[c == '#' for c in row] for row in D1], '2': [[c == '#' for c in row] for row in D2],
    }
    ink = {}
    for y in range(19, 30):                      # gradient colour per row; index 15 (black) is the outline/shadow
        vals = [pix[y * w + x] for x in range(0, 100) if pix[y * w + x] not in (0, 15)]
        ink[y] = collections.Counter(vals).most_common(1)[0][0] if vals else ink[y - 1]
    for y in range(16, 32):
        for x in range(0, 100):
            pix[y * w + x] = 0

    def put(text, x0):
        x = x0
        for c in text:
            if c == ' ':
                x += 4
                continue
            g = glyphs[c]
            for r, row in enumerate(g):
                for k, on in enumerate(row):
                    if on:
                        pix[(19 + r) * w + x + k] = ink[19 + r]
            x += len(g[0]) + 1
        return x - 1

    def shadow(x0, x1):                          # black outline one pixel right / below the letters, like the kana
        for y in range(19, 31):
            for x in range(x0, x1 + 2):
                if not pix[y * w + x]:
                    if (pix[(y - 1) * w + x] not in (0, 15)) or (pix[y * w + x - 1] not in (0, 15)) or (pix[(y - 1) * w + x - 1] not in (0, 15)):
                        pix[y * w + x] = 15
    e1 = put('SLOT 1', 3)
    e2 = put('SLOT 2', 51)
    shadow(3, e1)
    shadow(51, e2)
    assert e1 < 48 and e2 < 96, (e1, e2)
    os.makedirs(os.path.join(ROOT, 'build', 'gfx'), exist_ok=True)
    open(os.path.join(ROOT, 'build', 'gfx', 'open_474C0.bin'), 'wb').write(menu_gfx.pack(pix))
    im = Image.frombytes('P', (w, h), bytes(pix))
    pal = tim.palette(d, t)
    flat = [c for rgb in pal for c in rgb]
    im.putpalette(flat + [0] * (768 - len(flat)))
    im.convert('RGB').resize((w * 4, h * 4), Image.NEAREST).save(os.path.join(ROOT, 'translation', 'images', 'open_474C0_preview.png'))
    print(f'opentext: buttons drawn (SLOT 1 ends x={e1}, SLOT 2 ends x={e2}); data at {t["at"]:#x}')


if __name__ == '__main__':
    messages()
    buttons()
    print(f'opentext: {len(MSGS)} messages')
