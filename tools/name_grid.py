"""Name-entry character grid for the ABC mode (NAME.BIN, file offset 0x4400).

  python tools/name_grid.py     write build/name_grid.asm (included by name/feature.asm)

The grid is a table of 6 rows x 10 columns of u16 glyph indices (two 5-column panes). The original ABC page had
A-Z, 0-9 and / : - . Here the left pane keeps A-Z, the right pane gets a-z, and the spare cells hold
punctuation usable in names and a space (glyph 0, the full-width space). Digits are dropped: 52 letters + 10
digits do not fit in 60 cells.  Other pages (hiragana at 0x4478.., katakana, kanji pages) are untouched.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import etext  # noqa: E402

ROOT = etext.ROOT
TABLE = 0x4400            # file offset in NAME.BIN (RAM 0x800687C4)

UP = [chr(0xFF21 + i) for i in range(26)]
LO = [chr(0xFF41 + i) for i in range(26)]
LEFT_SYMS = ['．', '’', '－', '　']        # after Z:   . ' -  (space)
RIGHT_SYMS = ['！', '？', '／', '：']           # after z:   ! ? / :


def rows():
    left = UP + LEFT_SYMS            # 30 cells
    right = LO + RIGHT_SYMS          # 30 cells
    out = []
    for r in range(6):
        out.append(left[5 * r:5 * r + 5] + right[5 * r:5 * r + 5])
    return out


SYMS = [('．', '.'), ('－', '-'), ('！', '!'), ('？', '?'), ('／', '/'), ('：', ':'), ('＆', '&'), ('’', "'")]


def tables(o, nl):
    lc = [0] * 35
    for i in range(26):
        lc[etext.char2g[LO[i]] - 0x723] = 0x61 + i
    o.write(';; generated by tools/name_grid.py - full-width -> ASCII for typed names (vwf_name_map)' + nl)
    o.write('vwf_name_lc:' + nl + '    .byte ' + ', '.join(str(x) for x in lc) + nl)
    o.write('.align 2' + nl + 'vwf_name_sym:' + nl)
    for c, a in SYMS:
        o.write(f'    .halfword {etext.char2g[c]:#x}' + nl + f'    .byte {ord(a)}, 0' + nl)
    o.write('    .halfword 0, 0' + nl)


def main():
    nl = chr(10)
    with open(os.path.join(ROOT, 'build', 'name_vwf_tables.asm'), 'w', newline=nl) as o:
        tables(o, nl)
    with open(os.path.join(ROOT, 'build', 'name_grid.asm'), 'w', newline=nl) as o:
        o.write(';; generated by tools/name_grid.py - ABC page of the name entry grid' + nl)
        o.write(f'.org NAME_ADDR + {TABLE:#x}' + nl)
        for r in rows():
            o.write('    .halfword ' + ', '.join(f'{etext.char2g[c]:#x}' for c in r) + nl)
    print('name grid: 6x10, glyphs', ' '.join(''.join(r) for r in rows()))


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    main()
