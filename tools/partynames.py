"""Party member full names (family / given) in SLPS_005.00: the STATUS screen header, name inserts of the script interpreters.

  python tools/partynames.py     QA + generate build/partynames.asm (included by main.asm)

Origin: a table of 10-byte slots at 0x80049040 (index * 10), FF01-terminated glyph strings: 0 = "ATLUS" (default name), 1 =
"protagonist" (主人公), then family / given pairs of Maki (園村 麻希), Brown (上杉 秀彦), Nanjo (南条 圭), Mark (稲葉 正男), Elly (桐島 英理子),
Ayase (綾瀬 優香), Yukino (黛 ゆきの), Reiji (城戸 玲司). Read through the dialogue interpreters' name-insertion path (RAM
0x80076C68 in DNG; ADV 0x80066A94, S2D 0x80066B7C), i.e. as text: the VWF letters (ASCII + 0x68) like every dialogue string
(NOT the small-font codes of the nicknames: first try showed kana). A slot holds 8 letters + FF 01.
Names: glossary.tsv (Japanese order on screen: family name first, given name second).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import etext   # noqa: E402

ROOT = etext.ROOT
BASE = 0x80049040
SLOT = 10
NAMES = [
    'ATLUS', 'Hero',
    'Sonomura', 'Maki',
    'Uesugi', 'Hidehiko',
    'Nanjo', 'Kei',
    'Inaba', 'Masao',
    'K.', 'Eriko',              # Kirishima does not fit (8 letters + FF 01); user chose "K."
    'Ayase', 'Yuka',
    'Mayuzumi', 'Yukino',
    'Kido', 'Reiji',
]
OUT = os.path.join(ROOT, 'build', 'partynames.asm')
MAXCHARS = 8        # the name-insert opcodes of the script interpreters print 5 characters (ori v1,zero,5 -> sb v1,0x35(s1)); raised to 8



def enc(t):
    out = bytes(ord(c) + 0x68 for c in t) + bytes((0xFF, 0x01))      # VWF letters: ASCII + 0x68, read as dialogue text
    if len(out) > SLOT:
        raise SystemExit(f'partynames: {t!r} needs {len(out)} bytes (slot {SLOT})')
    return out + bytes(SLOT - len(out))


DEAD = {'ADV': 0x800662D4, 'DNG': 0x800761C4, 'S2D': 0x80065DB4}      # unreferenced functions (tools/deadovl.py), 80 bytes each


def overlay_patches():
    """name-insert opcodes: 5 -> 8 characters, except the hero (id 1): his typed name is 5 two-byte glyphs filling the whole
    10-byte slot without terminator (found 2026-10-08: "Perso" + "Son" of the next slot). At the two `sb v1,0x35(s1)` that store the
    count (delay slot = the following addiu v0,v0,-1, so the glue sees v0 = id - 1) a jal to dead-function glue sets 5 for the hero."""
    import struct
    for nm in ('ADV', 'DNG', 'S2D'):
        d = open(os.path.join(ROOT, 'original', nm + '.BIN'), 'rb').read()
        w = struct.unpack_from('<%dI' % (len(d) // 4), d, 0)
        nl = chr(10)
        lines = [';; generated by tools/partynames.py - do not edit']
        for i, x in enumerate(w):
            if x == 0x34030005 and any(w[j] == 0xA2230035 for j in range(i + 1, min(i + 12, len(w)))):
                lines.append('.org %#x%s    .byte %d' % (0x800643C4 + 4 * i, nl, MAXCHARS))
        sites = [0x800643C4 + 4 * i for i, x in enumerate(w) if x == 0xA2230035 and w[i + 1] == 0x2442FFFF and w[i - 1] == 0x24849040]
        assert len(lines) == 4 and len(sites) == 2, (nm, lines, sites)
        for a in sites:
            lines.append('.org %#x%s    jal     party_count_fix_%s' % (a, nl, nm.lower()))
        g = DEAD[nm]
        lines += ['.org %#x' % g, '.area 0x50',
                  'party_count_fix_%s:                ; v0 = id - 1 (hero = 0), v1 = 8' % nm.lower(),
                  '    li      t1, %d' % MAXCHARS,
                  '    bnez    v0, @@store',
                  '    nop',
                  '    li      t1, 5',
                  '@@store:',
                  '    jr      ra',
                  '    sb      t1, 0x35(s1)',
                  '.endarea']
        open(os.path.join(ROOT, 'build', 'partynames_%s.asm' % nm.lower()), 'w', newline=nl).write(nl.join(lines) + nl)


def main():
    overlay_patches()
    with open(OUT, 'w', newline=chr(10)) as o:
        o.write(';; generated by tools/partynames.py - do not edit' + chr(10))
        for i, t in enumerate(NAMES):
            o.write(f'.org {BASE + SLOT * i:#x}{chr(10)}    .byte ' + ', '.join(f'0x{x:02X}' for x in enc(t)) + chr(10))
    print(f'partynames: {len(NAMES)} slots -> {OUT}')


if __name__ == '__main__':
    main()
