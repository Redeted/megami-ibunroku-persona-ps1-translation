"""Clean Salt / Estoma: strongest demon level of every battle formation -> dng/estoma_levels.asm (committed).

  python tools/estoma.py [disc.bin]     regenerate (default disc: ../Megami Ibunroku Persona - Be Your True Mind (Japan).bin)
  python tools/estoma.py -v [disc.bin]  also print every formation

Formation data (found 2026-11-10): the dungeon writes the formation id (u16) to 0x801F5350; BTLP 0x80087D60 loads
its chunk of /B/D.BIN (sector offsets: u16 table BTLP 0x800DB9A0, chunk f = sectors t[f]..t[f+1], loaded to 0x80140000)
and reads 9 slots of 2 bytes from BTLP 0x800E8850 + f * 18 (position, entry index n; 0 = empty). Entry n = u32
pointer at chunk + (n - 1) * 8 (RAM address in the 0x80140000 image); the demon id is the high byte of the u16 at that
pointer + 2. Demon level = SLPS demon record 0x800417A0 + id * 0x38, byte +0x0A.
D.BIN is not part of original/ (38 MB), so the 360-byte result is committed; it only changes if the game data does.
"""
import csv
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import extract   # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DISC = os.path.join(os.path.dirname(ROOT), 'Megami Ibunroku Persona - Be Your True Mind (Japan).bin')
OUT = os.path.join(ROOT, 'dng', 'estoma_levels.asm')
BTLP_BASE = 0x800643C4
SLPS_BASE = 0x80010000 - 0x800
SECTORS, SLOTS = 0x800DB9A0, 0x800E8850
DEMONS, DEMON_STRIDE, LEVEL = 0x800417A0, 0x38, 0x0A
COUNT = 0x168                   # BTLP 0x8008011C: ids >= 0x168 are replaced by 0x10
NL = chr(10)


def read_dbin(disc):
    with open(disc, 'rb') as f:
        pvd = extract.read_sectors(f, 16, 2048)
        root_lba, root_size = struct.unpack_from('<I', pvd, 158)[0], struct.unpack_from('<I', pvd, 166)[0]
        for path, lba, size in extract.walk(f, root_lba, root_size):
            if path == 'B/D.BIN':
                return extract.read_sectors(f, lba, size)
    raise SystemExit('B/D.BIN not found on ' + disc)


def formations(dbin):
    b = open(os.path.join(ROOT, 'original', 'BTLP.BIN'), 'rb').read()
    t = [struct.unpack_from('<H', b, SECTORS - BTLP_BASE + 2 * i)[0] for i in range(COUNT + 1)]
    out = []
    for f in range(COUNT):
        ch = dbin[t[f] * 2048:t[f + 1] * 2048]
        ids = []
        for k in range(9):
            n = b[SLOTS - BTLP_BASE + f * 18 + 2 * k + 1]
            if not n:
                continue
            p = struct.unpack_from('<I', ch, (n - 1) * 8)[0] - 0x80140000
            ids.append(struct.unpack_from('<H', ch, p + 2)[0] >> 8)
        out.append(ids)
    return out


def main():
    args = [a for a in sys.argv[1:] if a != '-v']
    forms = formations(read_dbin(args[0] if args else DISC))
    s = open(os.path.join(ROOT, 'original', 'SLPS_005.00'), 'rb').read()
    level = lambda i: s[DEMONS + i * DEMON_STRIDE + LEVEL - SLPS_BASE]
    top = [max((level(i) for i in ids), default=255) for ids in forms]   # empty formation: never skipped
    with open(OUT, 'w', newline=NL) as o:
        o.write(';; generated by tools/estoma.py - strongest demon level per formation (255 = empty / never skip)' + NL)
        o.write(';; included under a label by dng/estoma.asm and s2d/estoma.asm' + NL)
        for i in range(0, COUNT, 20):
            o.write('    .byte ' + ', '.join(str(x) for x in top[i:i + 20]) + NL)
        o.write('.align 4' + NL)
    print(f'estoma: {COUNT} formations, {sum(1 for ids in forms if not ids)} empty -> {OUT}')
    if '-v' in sys.argv:
        names = {int(r['id']): r['en'] for r in
                 csv.DictReader(open(os.path.join(ROOT, 'translation', 'strings', 'DEMONS.tsv'), encoding='utf-8'),
                                delimiter='\t')}
        for f, ids in enumerate(forms):
            print(f, top[f], ', '.join(f'{names.get(i, i)} {level(i)}' for i in ids))


if __name__ == '__main__':
    main()
