;; =============================================================
;; BTLP.BIN - story-battle dialogue: byte-pair-encoded strings (tools/btlevt.py)
;;
;; The English story-battle lines need more room than their zone
;; (BTLEVT_ZONE_START..END), so they are stored byte-pair encoded:
;;   FF xx        control code, copied as is (FF F5 / FF EF end the string)
;;   88..E6       a VWF character (ASCII + 0x68), copied as is
;;   01..87,E7..FE  a pair code: expands to the two bytes btlevt_pairs[i]
;;                (which may be pair codes themselves)
;; Every message box goes through 0x8007D078(str), the only writer of the
;; text read pointer (text struct 0x800EB890 + 8). The hook there unpacks a
;; string of the zone into btlevt_buf and points the interpreter at it;
;; other strings are stored unchanged.
;; =============================================================

.org 0x8007D0B4                         ; was: lui at,0x800F ; sw s0,-0x4768(at)
    jal     btl_unpack
    move    a0, s0

.org BTLEVT_UNPACK_ADDR
.area BTLEVT_ZONE_END - BTLEVT_UNPACK_ADDR

;; a0 = string -> stores the (unpacked) read pointer, returns v0 = 1 (the caller's v0)
;; clobbers a0, v1, t0-t7, at
btl_unpack:
    addiu   sp, sp, -40
    la      t0, btlevt_pairs
    sw      t0, 32(sp)                  ; pair table of this string (the negotiation strings have their own: btl_neg)
    la      t0, BTLEVT_ZONE_START
    sltu    t1, a0, t0
    bnez    t1, btl_unpack_neg                   ; below the story-battle zone: maybe a packed negotiation string
    la      t0, BTLEVT_ZONE_END
    sltu    t1, a0, t0
    beqz    t1, btl_unpack_store
    nop
btl_unpack_go:
    la      t2, btlevt_buf              ; t2 = destination
    addiu   t6, sp, 28                  ; t6 = empty-stack mark (byte stack grows down inside our frame)
@@next:
    lbu     v0, 0(a0)
    addiu   a0, a0, 1
    li      t1, 0xFF
    bne     v0, t1, @@symbol
    nop
    lbu     v1, 0(a0)                   ; control code FF xx
    addiu   a0, a0, 1
    sb      v0, 0(t2)
    sb      v1, 1(t2)
    addiu   t2, t2, 2
    li      t1, 0xF5
    beq     v1, t1, @@done
    li      t1, 0xEF
    beq     v1, t1, @@done
    nop
    b       @@next
    nop
@@symbol:
    move    t5, t6
    sb      v0, 0(t5)                   ; push the symbol
    addiu   t5, t5, -1
@@expand:
    beq     t5, t6, @@next              ; stack empty
    nop
    addiu   t5, t5, 1
    lbu     v0, 0(t5)                   ; pop
    nop
    sltiu   t1, v0, 0x88
    bnez    t1, @@low                   ; 01..87: pair code
    sltiu   t1, v0, 0xE7
    bnez    t1, @@literal               ; 88..E6: character
    nop
    b       @@pair                      ; E7..FE: pair code
    addiu   v1, v0, 0x87 - 0xE7
@@low:
    addiu   v1, v0, -1
@@pair:
    sll     v1, v1, 1
    lw      t7, 32(sp)                  ; pair table
    nop
    addu    t7, t7, v1
    lbu     t1, 1(t7)                   ; right
    lbu     v1, 0(t7)                   ; left
    sb      t1, 0(t5)                   ; push right, then left (popped first)
    addiu   t5, t5, -1
    sb      v1, 0(t5)
    b       @@expand
    addiu   t5, t5, -1
@@literal:
    sb      v0, 0(t2)
    b       @@expand
    addiu   t2, t2, 1
@@done:
    la      a0, btlevt_buf
btl_unpack_store:
    lui     at, 0x800F
    sw      a0, -0x4768(at)             ; text struct read pointer (0x800EB898)
    addiu   sp, sp, 40
    jr      ra
    li      v0, 1
btl_unpack_neg:
    j       btl_neg                     ; tools/btlneg.py (BTLP dead function): marker byte 0 + own pair table
    nop

btlevt_pairs:
.include "build/btlevt_pairs.asm"       ; generated by tools/btlevt.py
.align 4
btlevt_buf:
    .fill BTLEVT_BUF_SIZE, 0
.endarea
