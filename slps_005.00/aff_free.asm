.org AFF_FREE2_ADDR
.area AFF_FREE_END - AFF_FREE2_ADDR

;; -------------------------------------------------------------
;; vwf_glyph_map(a0 = glyph code as passed to vwf_dialog_emit, a1 = 1 on the name-insertion path)
;; Name insertions (<FF13> arcana, <FF0C> Persona / demon / item names ...) copy small-font table bytes, whose
;; English letters are small-font codes, not VWF bytes: map them through vwf_small_map. Everything else (and
;; unmapped codes, i.e. Japanese) goes on to vwf_name_map. Returns v0; clobbers t0-t6 like vwf_name_map.
;; -------------------------------------------------------------
vwf_glyph_map:
    beqz    a1, @@other
    sltiu   t0, a0, VWF_SMALL_MAP_LEN
    beqz    t0, @@other
    nop
    la      t1, vwf_small_map
    addu    t1, t1, a0
    lbu     t1, 0(t1)
    nop
    beqz    t1, @@other
    nop
    jr      ra
    addiu   v0, t1, VWF_CHAR_BIAS
@@other:
    j       vwf_name_map
    nop

vwf_small_map:
.include "build/vwf_small_map.asm"      ; generated by tools/fusionmsg.py

