;; =============================================================
;; SLPS_005.00 - full-length skill names (tools/skills.py)
;;
;; A skill record (0x80047D44 + id*0x14) keeps the first 10 glyphs of the
;; English name. Longer names continue in the record's unused bytes
;; +0x11..+0x13 (up to 3 glyphs, FF-terminated when shorter) or, for 4-5 more
;; glyphs, FE + offset into skill_tails_x (glyphs + FF).
;; skill_name_copy writes exactly 15 glyphs (name, then blank glyph 0).
;; Lives in an unreferenced SLPS function (tools/deadfuncs.py), resident.
;; =============================================================

.org SKILL_CODE_ADDR
.area SKILL_CODE_SIZE

;; a0 = destination (15 bytes), a1 = skill id (1-based)
;; clobbers v0, v1, a0, a1, a2, at only (callers rely on this: t*/a3 are live)
skill_name_copy:
    sll     v0, a1, 2
    addu    v0, v0, a1
    sll     v0, v0, 2                   ; id * 0x14
    la      v1, SKILL_RECORDS_ADDR
    addu    v1, v1, v0                  ; v1 = record (name field)
    li      a1, SKILL_FIELD             ; a1 = glyph count where this phase stops
    move    a2, zero                    ; a2 = glyphs written
@@copy:
    beq     a2, a1, @@phase_end
    nop
    lbu     v0, 0(v1)
    li      at, 0xFF
    beq     v0, at, @@pad
    addiu   v1, v1, 1
    sb      v0, 0(a0)
    addiu   a0, a0, 1
    b       @@copy
    addiu   a2, a2, 1
@@phase_end:
    li      at, SKILL_FIELD
    bne     a2, at, @@pad               ; the tail phase ended (13 or 15 glyphs)
    nop
    addiu   v1, v1, SKILL_SPARE - SKILL_FIELD   ; record + 0x11
    lbu     v0, 0(v1)
    li      at, 0xFE
    bne     v0, at, @@copy              ; inline tail: up to 3 glyphs
    li      a1, SKILL_FIELD + 3
    lbu     v0, 1(v1)
    la      v1, skill_tails_x
    addu    v1, v1, v0
    b       @@copy                      ; overflow tail: up to 5 glyphs, FF-terminated
    li      a1, SKILL_MAXLEN
@@pad:
    li      at, SKILL_MAXLEN
@@pad_loop:
    beq     a2, at, @@done
    nop
    sb      zero, 0(a0)
    addiu   a0, a0, 1
    b       @@pad_loop
    addiu   a2, a2, 1
@@done:
    jr      ra
    nop

.endarea

