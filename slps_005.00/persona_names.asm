;; =============================================================
;; SLPS_005.00 - full-length Persona names (tools/personas.py)
;;
;; Same scheme as skill_names.asm: the master record (0x8004B0CC + id*0x2C)
;; keeps the first 10 glyphs at +8; longer names continue in the unused
;; bytes +0x29..+0x2B (up to 3 glyphs) or FE + offset into persona_tails_x.
;; persona_name_copy writes exactly 16 glyphs (name, then blank glyph 0).
;; Reads the master table by id, so Personas obtained before the patch
;; (whose party-data copy of the name is still Japanese) show English too.
;; =============================================================

.org PERSONA_CODE_ADDR
.area PERSONA_CODE_SIZE

;; a0 = destination (16 bytes), a1 = Persona id (1-based)
;; clobbers v0, v1, a0, a1, a2, at only (same contract as skill_name_copy)
persona_name_copy:
    sll     v0, a1, 1
    addu    v0, v0, a1
    sll     v0, v0, 2
    subu    v0, v0, a1                  ; id * 11
    sll     v0, v0, 2                   ; id * 0x2C
    la      v1, PERSONA_RECORDS_ADDR + PERSONA_NAME
    addu    v1, v1, v0                  ; v1 = name field
    li      a1, PERSONA_FIELD           ; a1 = glyph count where this phase stops
    move    a2, zero                    ; a2 = glyphs written
@@copy:
    beq     a2, a1, @@phase_end
    lbu     v0, 0(v1)                   ; (harmless when the branch is taken)
    li      at, 0xFF
    beq     v0, at, @@pad
    addiu   v1, v1, 1
    sb      v0, 0(a0)
    addiu   a0, a0, 1
    b       @@copy
    addiu   a2, a2, 1
@@phase_end:
    li      at, PERSONA_FIELD
    bne     a2, at, @@pad               ; the tail phase ended
    addiu   v1, v1, PERSONA_SPARE - PERSONA_NAME - PERSONA_FIELD   ; record + 0x29 (harmless if taken)
    lbu     v0, 0(v1)
    li      at, 0xFE
    bne     v0, at, @@copy              ; inline tail: up to 3 glyphs
    li      a1, PERSONA_FIELD + 3
    lbu     v0, 1(v1)
    la      v1, persona_tails_x
    addu    v1, v1, v0
    b       @@copy                      ; overflow tail, FF-terminated
    li      a1, PERSONA_MAXLEN
@@pad:
    li      at, PERSONA_MAXLEN
@@pad_loop:
    beq     a2, at, @@done
    nop
    sb      zero, 0(a0)
    addiu   a0, a0, 1
    b       @@pad_loop
    addiu   a2, a2, 1
@@done:
    jr      ra
    nop

.endarea

.org PERSONA_TAILS_ADDR
.area PERSONA_TAILS_SIZE
persona_tails_x:
.include "build/persona_tails.asm"      ; generated by tools/personas.py
.endarea

.org PERSONA_HDR_BUF                    ; battle skill menu header: Persona name (16 glyphs); the PRS-CHG window
.area 48                                ; (never open at the same time) uses all three 16-byte slots: NOW, SUB, SUB
    .fill 48, 0
.endarea
